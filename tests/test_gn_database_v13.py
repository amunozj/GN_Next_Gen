"""Invariants of the frozen v1.3 observation database, release v1.3_4.

Several of these are *characterization* tests rather than correctness tests: they
pin the known data issues D16-D20 at their measured values so the numbers quoted in
the data dictionary, the folder README and the report to the v1.3 authors cannot
drift unnoticed. If one of them fails, the data changed -- check whether the
documentation and the report still say the right thing before relaxing it.

The committed tables are built from **v1.3_4** (ADR-010), which fixed most of what
``docs/results/gn-v13-feedback-report.md`` reported upstream. Each issue below
therefore records both numbers: what _4 shows, and what _3 showed. ``v1.3_3``'s own
figures are pinned by ``test_v133_still_reproduces`` (slow), which regenerates them
from the retained workbook -- that test is what makes ADR-010's third condition real.
"""

