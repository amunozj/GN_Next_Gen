def test_both_release_workbooks_present():
    """ADR-010's first condition: every release's source artifact is retained."""
    for name, path in GN_V13_RELEASES.items():
        assert path.is_file(), f"release {name} workbook must stay beside the conversion"
    assert GN_V13_XLSX == GN_V13_RELEASES[GN_V13_CURRENT_RELEASE]


def test_rows_are_date_sorted(obs):
    """v1.3_4 ships its observations in date order; _3 did not.

    Worth pinning because it is why the derived parquet is 40% smaller than the
    _3-derived file it replaced: sorted ORDINAL and FRACYEAR columns compress far
    better, while STATION compresses worse.
    """
    assert obs["ORDINAL"].is_monotonic_increasing


def test_schema(obs, observers):
    assert list(obs.columns) == [
        "YEAR",
        "MONTH",
        "DAY",
        "ORDINAL",
        "STATION",
        "OBSER",
        "GROUPS",
        "FRACYEAR",
        "SHEET",
    ]
    assert list(observers.columns) == [
        "STATION",
        "INITIAL",
        "FINAL",
        "TOT_OBS",
        "OBSERVER",
        "changed_in_v13",
    ]


def test_row_counts(obs, observers):
    assert len(obs) == TOTAL_ROWS
    assert int((obs["STATION"] > 0).sum()) == STATION_ROWS
    assert obs.loc[obs["STATION"] > 0, "STATION"].nunique() == STATIONS_WITH_DATA
    assert len(observers) == OBSERVERS_LISTED


def test_sheet_row_counts_and_no_blank_rows(obs):
    """The 1610-1946 sheet has ~96,000 trailing blank rows; none may survive."""
    assert obs.groupby("SHEET").size().to_dict() == SHEET_ROWS
    assert obs["YEAR"].notna().all()
    assert obs["ORDINAL"].notna().all()


def test_sheet_seams_do_not_gap_or_overlap(obs):
    """The three sheets must tile 1610-2010 exactly at 1946/1947 and 1988/1989."""
    spans = obs.groupby("SHEET")["YEAR"].agg(["min", "max"]).to_dict("index")
    assert spans["1610-1946"]["min"] == 1610
    for earlier, later in (("1610-1946", "1947-1988"), ("1947-1988", "1989-2010")):
        assert spans[earlier]["max"] + 1 == spans[later]["min"], (earlier, later, spans)
    assert spans["1989-2010"]["max"] == 2010


def test_coverage_and_no_invalid_dates(obs):
    assert obs["ORDINAL"].min() == dt.date(1610, 1, 1).toordinal()
    assert obs["ORDINAL"].max() == dt.date(2010, 12, 31).toordinal()
    # ORDINAL must round-trip to (YEAR, MONTH, DAY) for every row.
    sample = obs.sample(5000, random_state=0)
    rebuilt = [dt.date.fromordinal(int(o)) for o in sample["ORDINAL"]]
    assert all(
        (d.year, d.month, d.day) == (y, m, dd)
        for d, y, m, dd in zip(rebuilt, sample["YEAR"], sample["MONTH"], sample["DAY"], strict=True)
    )


def test_ordinal_matches_v122_convention(obs):
    """1610-01-01 = 587676, as the v1.22 data dictionary records."""
    first = obs.loc[obs["ORDINAL"] == obs["ORDINAL"].min()].iloc[0]
    assert int(first["ORDINAL"]) == 587_676


def test_leap_days_absent(obs):
    """Feb 29 of 1700/1800/1900 is not a Gregorian leap day; v1.21 removed them."""
    bad = obs[(obs["MONTH"] == 2) & (obs["DAY"] == 29) & obs["YEAR"].isin([1700, 1800, 1900])]
    assert bad.empty


def test_sentinels(obs):
    """GROUPS = -1 only ever accompanies STATION = 0, and vice versa."""
    assert (obs.loc[obs["STATION"] > 0, "GROUPS"] >= 0).all()
    assert (obs.loc[obs["STATION"] == 0, "GROUPS"] == -1).all()


def test_every_station_with_data_is_listed(obs, observers):
    with_data = set(obs.loc[obs["STATION"] > 0, "STATION"].unique())
    assert with_data <= set(observers["STATION"])
    assert observers["STATION"].min() == 1
    assert observers["STATION"].max() == OBSERVERS_LISTED


# --- characterization of the known issues ----------------------------------


def test_d16_duplicate_date_station_keys(obs):
    """3 duplicate keys survive in _4, only 1 conflicting -- see D16.

    _3 had 217 keys and 95 conflicts, concentrated in stations 755, 329 and 245;
    _4 cleared those three entirely. What is left is Wolf (773) twice with
    GROUPS = 0 both times, and Takuma (768) on 1982-10-13 with 8 against 7 --
    the single conflict the loader's ``duplicate_rule`` has to resolve.
    """
    rows = obs[obs["STATION"] > 0]
    dups = rows[rows.duplicated(["ORDINAL", "STATION"], keep=False)]
    keys = dups.groupby(["ORDINAL", "STATION"])["GROUPS"].nunique()
    assert len(keys) == 3
    assert int((keys == 1).sum()) == 2
    assert int((keys > 1).sum()) == 1
    by_station = dups.groupby(["ORDINAL", "STATION"]).size().reset_index()
    assert by_station["STATION"].value_counts().to_dict() == {773: 2, 768: 1}

    conflict = dups[dups["STATION"] == 768]
    assert sorted(conflict["GROUPS"]) == [7, 8]
    assert {(int(r.YEAR), int(r.MONTH), int(r.DAY)) for r in conflict.itertuples()} == {
        (1982, 10, 13)
    }


def test_d17_extreme_group_counts(obs):
    """_4 removed the implausible 93; one row above 53 remains -- see D17.

    The 58 (1992-03-18, station 712 Watukosek) is inherited unchanged from v1.22 at
    an unflagged station, so it stays. State-space truncation K still comes from a
    robust quantile, never from this maximum.
    """
    real = obs[obs["STATION"] > 0]
    extreme = real[real["GROUPS"] > 53]
    assert len(extreme) == 1
    got = {
        (int(r.YEAR), int(r.MONTH), int(r.DAY), int(r.STATION), int(r.GROUPS))
        for r in extreme.itertuples()
    }
    assert got == {(1992, 3, 18, 712, 58)}
    assert not (real["GROUPS"] == 93).any(), "the 93 was a transcription slip and _4 removed it"
    assert int(real["GROUPS"].max()) == 58


def test_d17_robust_truncation_rule(obs):
    """K = 41 satisfies the plan's rule under this release, and under _3.

    Rule: the smallest K with P(GROUPS >= K) < 1e-5, and K above the largest
    reference daily count (31, KMAS). _4's minimum is 39 and _3's was 41, so 41 is
    the value stable across both releases -- which is why the plan adopted it.
    """
    groups = obs.loc[obs["STATION"] > 0, "GROUPS"]
    k = 41
    assert (groups >= k).mean() < 1e-5
    assert k > 31
    assert int(groups.quantile(0.9999)) == 25


def test_d18_placeholder_observers(observers):
    """34 observers are listed with no observations -- see D18.

    _3 carried the *string* ``'NA'`` for their years, which loaders had to accept;
    _4 leaves them blank, so the non-numeric sentinel is gone and the same coercion
    yields nulls either way.
    """
    placeholder = observers[observers["TOT_OBS"] == 0]
    assert len(placeholder) == PLACEHOLDER_OBSERVERS
    assert placeholder["INITIAL"].isna().all()
    assert placeholder["FINAL"].isna().all()
    active = observers[observers["TOT_OBS"] > 0]
    assert len(active) == OBSERVERS_LISTED - PLACEHOLDER_OBSERVERS
    assert active["INITIAL"].notna().all()
    assert (active["FINAL"] >= active["INITIAL"]).all()


def test_d20_change_flags_from_explicit_column(observers):
    """100 observers are flagged by _4's explicit column -- see D20.

    In _3 this existed nowhere but green cell fill, which is why the converter had
    to read fills at all. _4 adds ``CHANGED IN v1.3 (1=YES, 0=NOT)``, which wins.
    The fill still marks 99 and disagrees on exactly one station -- 36, MOUTON of
    Lyon, a placeholder with no observations -- which is a finding for the authors,
    not a conversion error. ``tests/test_gn_database_v13_convert.py`` pins the
    comparison itself.
    """
    assert int(observers["changed_in_v13"].sum()) == CHANGED_IN_V13
    assert bool(observers.loc[observers["STATION"] == 36, "changed_in_v13"].iloc[0])


def test_changelog_blocks(changelog):
    assert list(changelog.columns) == ["version", "name", "year", "note"]
    assert changelog["version"].value_counts().to_dict() == CHANGELOG_COUNTS
    v13 = changelog[changelog["version"] == "v1.3"]
    assert v13["note"].notna().all()
    # D7's correction literature must actually be cited in the v1.3 block.
    notes = " ".join(v13["note"].astype(str))
    for author in ("Hayakawa", "Carrasco", "Neuh", "Vokhmyanin"):
        assert author in notes, author


# --- ADR-010: the superseded release stays reproducible --------------------


@pytest.mark.slow
def test_v133_still_reproduces(tmp_path):
    """Regenerate v1.3_3 from its retained workbook and check its own figures.

    This is ADR-010's third condition made real: ``data/raw`` carries only the current
    release's tables, so the numbers in ``docs/results/raw-data-renovation.md`` and in
    the report to the v1.3 authors are reproducible only if this works. It parses a
    28 MB workbook, hence slow.
    """
    import subprocess
    import sys

    from gn_next_gen.paths import REPO_ROOT, SCRIPTS

    proc = subprocess.run(
        [
            sys.executable,
            str(SCRIPTS / "convert_gn_database_v13.py"),
            "--release",
            "v1.3_3",
            "--out-dir",
            str(tmp_path),
        ],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    assert proc.returncode == 0, proc.stderr[-2000:]

    obs = pd.read_parquet(tmp_path / "gn_v13_observations.parquet")
    observers = pd.read_parquet(tmp_path / "gn_v13_observers.parquet")
    changelog = pd.read_csv(tmp_path / "gn_v13_changelog.csv")

    assert len(obs) == V133["total_rows"]
    assert int((obs["STATION"] > 0).sum()) == V133["station_rows"]
    assert obs.loc[obs["STATION"] > 0, "STATION"].nunique() == V133["stations_with_data"]
    assert obs.groupby("SHEET").size().to_dict() == V133["sheet_rows"]
    assert int(obs.loc[obs["STATION"] > 0, "GROUPS"].max()) == V133["max_groups"]
    assert len(observers) == V133["observers_listed"]
    assert int(observers["changed_in_v13"].sum()) == V133["changed_in_v13"]
    assert int((observers["TOT_OBS"] == 0).sum()) == V133["placeholder_observers"]
    assert changelog["version"].value_counts().to_dict() == V133["changelog_counts"]

    real = obs[obs["STATION"] > 0]
    keys = real[real.duplicated(["ORDINAL", "STATION"], keep=False)]
    keys = keys.groupby(["ORDINAL", "STATION"])["GROUPS"].nunique()
    assert len(keys) == V133["dup_keys"]
    assert int((keys > 1).sum()) == V133["dup_conflicting"]

    # Identical schema to the current release, which is what lets loaders ignore it.
    current = pd.read_parquet(GN_V13_OBSERVATIONS)
    assert list(obs.columns) == list(current.columns)
